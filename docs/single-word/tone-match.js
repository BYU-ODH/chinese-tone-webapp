/*
 * tone-match.js — how close is this production to the tone it is aiming at?
 *
 * This module exists so that the band a learner sees and the judgement they
 * receive are the SAME OBJECT. Today they are not: viz.js draws a fixed 32-pixel
 * stroke around the target curve, classifier.js scores Legendre coefficients
 * through hand-tuned rules, and nothing connects them — so a contour drawn
 * entirely inside the band can be marked wrong, and (seven times more often, in
 * the measurement that prompted this) a contour drawn outside it can be marked
 * right. See EVALUATION_PLAN.md for the numbers.
 *
 * THE GUARANTEE. The verdict keys on RMS deviation from a reference contour,
 * and the band viz.js draws is a tube of exactly that radius. A tube of
 * half-width r contains only curves whose RMS deviation from its centre is
 * <= r, so a line drawn entirely inside the band is GUARANTEED to score
 * 'good'. That property is the whole point of this module and must survive any
 * retuning: the moment the verdict keys on something the band does not express,
 * the display starts lying again.
 *
 * IT IS SUFFICIENT, NOT NECESSARY, and the UI must not imply otherwise. RMS
 * averages, so a contour may stray outside the band at one point and still pass;
 * measured on the corpus, 27% of productions marked 'good' are drawn leaving the
 * band somewhere. Read the band as "stay in here and you are definitely right",
 * never as "leave here and you are wrong". Making it necessary too is possible —
 * cap the single-point excursion — and was measured and declined, because it
 * marks more than half of correct native third tones wrong to tidy up a
 * direction nobody complains about. scripts/build-tone-modes.mjs's
 * EXCURSION_CAP has the numbers and the reasoning.
 *
 * WHAT THIS MODULE DOES NOT DO: tone identity. It answers "how close to the
 * target is this?", never "which tone was this?" — classifier.js answers that,
 * and writes every diagnostic sentence.
 *
 * That split was originally justified by the rules simply being better at
 * identity. Against a REGISTER-AWARE corpus they are not: nearest-shape geometry
 * scores 88.8% leave-one-speaker-out against the rules' 85.2%, and 87% against
 * 79% on T3. The split survives on different grounds — the rules remain better
 * in the SHAPE-ONLY regime (83.0% against 81.4%), which is what an uncalibrated
 * learner is scored in, and they carry diagnostic knowledge this module has no
 * equivalent of. Keeping both means neither regime is left to the model that is
 * worse at it.
 *
 * ACCEPTED REALIZATIONS. A tone may carry more than one reference shape, because
 * the mean of a multimodal distribution is a target nobody hits. How many is
 * MEASURED per tone, not assumed (scripts/build-tone-modes.mjs), and the answer
 * changed once register was available: T1, T2 and T4 need only one shape, and
 * only T3 keeps two — the full dipping third and the half-third. In the
 * shape-only regime every tone appeared to need two or three, which in hindsight
 * was the fit spending clusters on register variation it could not see directly.
 *
 * REGISTER TOLERANCE. Every match allows a bounded vertical shift (±2 ST by
 * default), so a speaker who sits a little low is scored on shape rather than
 * punished for register, while the bound stops the slack from sliding one tone
 * onto another.
 *
 * TOLERANCES ARE A MEASURED TRADEOFF, not a geometric rule: each is the widest
 * band that still accepts no more than 5% of productions of the OTHER three
 * tones. At those widths the bands accept 100% (T1), 97% (T2), 68% (T3) and 91%
 * (T4) of correct native productions.
 *
 * KNOWN LIMITATION, recorded rather than hidden: T3 is the holdout at 68%.
 * Roughly a third of correct native third tones fall outside its band, and no
 * tolerance fixes it — widening to catch them starts admitting T2 productions
 * first (at ±2.5 ST it lets in 63% of them). Register nearly doubled T3's
 * coverage, from 37%, so the remaining gap is not a register problem; T3 is
 * simply produced across a wider spread than this geometry captures. Treat a T3
 * verdict from this module as weaker evidence than the other three, and lean on
 * classifier.js there.
 */

