/** Vertical slack allowed when aligning a production to a reference, semitones. */
export const MAX_SHIFT_ST = 2.0;

/**
 * How much vertical slack a production actually gets.
 *
 * UNTRUSTED REGISTER MEANS UNBOUNDED SLACK. Until the speaker reference has
 * stabilized, features.js normalizes a contour to the speaker's own median
 * rather than to their register, so c0 is ~0 for every tone regardless of how
 * high or low it was actually sung. Scoring that against a reference anchored at
 * an absolute height (+5 ST for T1) charges the speaker a 5 ST register error
 * they did not make: measured on the full corpus, bounding the shift in this
 * regime marks **100% of native T1 productions 'bad'**. Both existing consumers
 * already handle this — classifier.js zeroes its register-dependent rules, and
 * viz.js recentres the drawn contour on the band mean — and this is the same
 * decision expressed as a shift limit.
 *
 * The cost is real and is the reason calibration exists: with unbounded slack, a
 * level tone sung low is indistinguishable from one sung high, so T1 and T3 are
 * separated by shape and duration alone. That is not a regression — classify()
 * has exactly the same blind spot in the same regime — but it is why
 * matchUtterance solves ONE shift for the whole utterance rather than one per
 * syllable: relative height between syllables survives even when absolute
 * height is unknowable.
 *
 * `registerTrusted` is read strictly: only an explicit `false` means untrusted.
 * extractSyllableFeatures() always sets the field, so the permissive default
 * only affects synthetic feature structs in tests.
 */
export function shiftLimitFor (features, maxShift = MAX_SHIFT_ST) {
  return (features && features.registerTrusted === false) ? Infinity : maxShift;
}

/**
 * Sampling resolution for every contour comparison in this module. Fixed and
 * shared: the deviation integral, the band viz.js draws, and the fitted modes
 * must all be sampled identically or the tube's radius stops matching the
 * verdict's threshold and the guarantee above quietly breaks.
 */
export const SAMPLES = 41;

const TS = Array.from({ length: SAMPLES }, (_, i) => -1 + 2 * i / (SAMPLES - 1));

/*
 * Slack on the tolerance comparisons, semitones. The band is drawn as a filled
 * tube, so a contour resting exactly on its edge reads as inside it, and the
 * guarantee at the top of this file says inside must mean 'good'. Without this,
 * a contour whose deviation is exactly the tolerance fails by one part in 1e15:
 * `deviation` accumulates 41 squared residuals and takes a square root, so it
 * lands a hair above a tolerance written as a short decimal literal. Far too
 * small to affect any real production, and it is what makes the boundary
 * inclusive rather than a coin toss.
 */
const EPSILON = 1e-9;

function legendreBasis (t) {
  return [1, t, (3 * t * t - 1) / 2, (5 * t * t * t - 3 * t) / 2];
}

/**
 * Sample a Legendre coefficient vector [c0..c3] across normalized time.
 * Returns SAMPLES values in semitones re speaker mean, t running 0..1.
 */
export function sampleCoefs (coefs) {
  const out = new Array(SAMPLES);
  for (let i = 0; i < SAMPLES; i++) {
    const b = legendreBasis(TS[i]);
    let y = 0;
    for (let k = 0; k < 4; k++) y += (coefs[k] || 0) * b[k];
    out[i] = y;
  }
  return out;
}

/**
 * Deviation of contour `a` from reference `b` after the best vertical shift.
 *
 * The shift is the least-squares one — the mean residual — clamped to
 * ±maxShift. Clamping is load-bearing, not defensive: an unbounded shift would
 * let a low level tone slide up onto the high level tone's reference and score
 * perfectly. Pass maxShift = 0 to compare at absolute register.
 *
 * @returns {{shift:number, clamped:boolean, rms:number, max:number}} semitones
 */
export function deviation (a, b, maxShift = MAX_SHIFT_ST) {
  const n = Math.min(a.length, b.length);
  let want = 0;
  for (let i = 0; i < n; i++) want += b[i] - a[i];
  want /= n;
  const shift = Math.max(-maxShift, Math.min(maxShift, want));
  let ss = 0;
  let mx = 0;
  for (let i = 0; i < n; i++) {
    const e = a[i] + shift - b[i];
    ss += e * e;
    if (Math.abs(e) > mx) mx = Math.abs(e);
  }
  return {
    shift,
    clamped: Math.abs(want) > maxShift + 1e-9,
    rms: Math.sqrt(ss / n),
    max: mx
  };
}

/**
 * Build the accepted realizations for one (syllable, tone).
 *
 * The SHAPE of each reference comes from the fitted modes; its HEIGHT (c0)
 * comes from `targetEntry` — a getSyllableTargets() entry for this syllable, or
 * null to use the tone's canonical height. That split is forced by the data:
 * the corpus feature cache normalizes every clip to its own median, so its c0
 * carries no register information to fit, while targets.json's c0 is genuine
 * semitones-re-speaker-mean. The bounded shift absorbs what the split leaves
 * imprecise. Documented in scripts/build-tone-modes.mjs; revisit if a
 * register-aware cache is ever built.
 *
 * @param {number} tone 1..4. Tone 0 (neutral) has no validated target and
 *   returns [] — callers must not draw or score a band for it, matching
 *   classifier.js's tone-0 guard.
 * @param {{coefs:number[], dur?:number}|null} targetEntry
 * @returns {Array<{tone, coefs, dur, curve, tolerance, share}>}
 */
export function buildReferences (tone, targetEntry = null) {
  const mode = TONE_MODES[tone];
  if (!mode) return [];
  const total = mode.shapes.reduce((a, s) => a + s.n, 0);
  return mode.shapes.map(s => {
    // When the modes were fitted against a per-speaker register reference they
    // carry their own height and need no external anchor. When they were fitted
    // shape-only, coefs[0] is 0 and the height comes from the per-syllable
    // target (or stays 0, which pairs with the unbounded slack an untrusted
    // register already gets — see shiftLimitFor).
    const anchor = MODES_CARRY_REGISTER
      ? s.coefs[0]
      : (Number.isFinite(targetEntry?.coefs?.[0]) ? targetEntry.coefs[0] : 0);
    const coefs = [anchor, s.coefs[1], s.coefs[2], s.coefs[3]];
    return {
      tone,
      coefs,
      dur: s.dur,
      curve: sampleCoefs(coefs),
      tolerance: mode.tolerance,
      share: s.n / total
    };
  });
}

/**
 * Match one syllable's contour against its accepted realizations.
 *
 * @param {object} features  an extractSyllableFeatures() struct. Unvoiced
 *   syllables return a null match rather than a verdict — there is nothing to
 *   be close to.
 * @param {Array} refs       from buildReferences()
 * @param {object} [opts]
 * @param {number} [opts.shift]  impose this vertical shift instead of solving
 *   for one. Pass the utterance-wide shift from matchUtterance() so every
 *   syllable in a phrase is judged at the same register.
 * @param {number} [opts.maxShift]
 * @param {number[]} [opts.contour]  compare this sampled contour instead of the
 *   one derived from features.coefs. Lets a caller score the raw displayed
 *   contour rather than its Legendre fit; note the shipped tolerances were
 *   measured against fits, so raw contours will read as worse until they are
 *   re-derived.
 * @returns {null|{ref, refIndex, shift, shiftClamped, rms, max, verdict,
 *   durationRatio, durationOk, band}}
 */
export function matchSyllable (features, refs, opts = {}) {
  if (!features || !features.voiced || !refs || refs.length === 0) return null;

  const contour = opts.contour || sampleCoefs(features.coefs);
  const requested = Number.isFinite(opts.maxShift) || opts.maxShift === Infinity
    ? opts.maxShift
    : MAX_SHIFT_ST;
  const maxShift = shiftLimitFor(features, requested);

  let best = null;
  refs.forEach((ref, refIndex) => {
    const d = Number.isFinite(opts.shift)
      ? fixedShiftDeviation(contour, ref.curve, opts.shift)
      : deviation(contour, ref.curve, maxShift);
    if (!best || d.rms < best.d.rms) best = { ref, refIndex, d };
  });

  const { ref, refIndex, d } = best;
  const verdict = d.rms <= ref.tolerance.good + EPSILON
    ? 'good'
    : (d.rms <= ref.tolerance.close + EPSILON ? 'close' : 'bad');

  /* Duration is REPORTED, never folded into the verdict. The complaint that
   * started this module was a contour drawn inside the band and marked wrong,
   * and the dominant cause was classifier.js's duration gate: a perfectly
   * shaped T4 scores 1.00 at 100 voiced frames and 0.49 — 'bad' — at 160,
   * with nothing on the canvas showing it. A hidden scoring dimension is
   * exactly what the guarantee at the top of this file forbids. Duration is a
   * real tone cue and callers should surface it; they must surface it, not
   * silently score it. */
  const durationRatio = ref.dur > 0
    ? (features.voicedFrameCount || 0) / ref.dur
    : null;
  const durationOk = durationRatio === null
    ? null
    : (durationRatio >= 0.6 && durationRatio <= 1.8);

  return {
    ref,
    refIndex,
    shift: d.shift,
    shiftClamped: d.clamped,
    rms: d.rms,
    max: d.max,
    verdict,
    durationRatio,
    durationOk,
    band: bandFor(ref)
  };
}

/** Deviation with an externally imposed shift (no solving, no clamping). */
function fixedShiftDeviation (a, b, shift) {
  const n = Math.min(a.length, b.length);
  let ss = 0;
  let mx = 0;
  for (let i = 0; i < n; i++) {
    const e = a[i] + shift - b[i];
    ss += e * e;
    if (Math.abs(e) > mx) mx = Math.abs(e);
  }
  return { shift, clamped: false, rms: Math.sqrt(ss / n), max: mx };
}

/**
 * What viz.js draws: the reference contour and the two tube radii, in
 * semitones, sampled on the same grid the verdict is computed over.
 */
export function bandFor (ref) {
  return {
    curve: ref.curve,
    good: ref.tolerance.good,
    close: ref.tolerance.close
  };
}

/**
 * Match every syllable of an utterance under ONE shared vertical shift.
 *
 * A per-syllable shift would let each syllable slide independently, which
 * destroys the relative-height cue between syllables — the thing that actually
 * distinguishes a phrase's high tones from its low ones, and the reason a
 * learner who says every tone at the same pitch should not score well. One
 * shift per utterance moves the whole phrase and leaves its internal structure
 * intact.
 *
 * Two passes: solve each syllable freely to find which realization it is aiming
 * at and what shift it wants, take the MEDIAN of those wants (robust to one
 * mistracked syllable), clamp it, then re-match everything at that fixed shift.
 *
 * @param {object[]} syllables  extractSyllableFeatures() structs, in order
 * @param {Array[]} refsPerSyllable  buildReferences() output per syllable; an
 *   empty array marks a neutral/unscored position and yields a null match
 * @returns {{shift:number, shiftClamped:boolean, matches:Array}}
 */
export function matchUtterance (syllables, refsPerSyllable, opts = {}) {
  const requested = Number.isFinite(opts.maxShift) ? opts.maxShift : MAX_SHIFT_ST;

  /* One limit for the whole utterance, from the syllables themselves: if the
   * register was untrusted for any of them it was untrusted for all (they share
   * one normalizer within an utterance), and the shared shift must be free to
   * absorb the missing register anchor. */
  const maxShift = syllables.some(f => f && f.registerTrusted === false)
    ? Infinity
    : requested;

  const wants = [];
  syllables.forEach((f, i) => {
    const m = matchSyllable(f, refsPerSyllable[i], { maxShift: Infinity });
    if (m) wants.push(m.shift);
  });

  let shift = 0;
  let clamped = false;
  if (wants.length) {
    wants.sort((a, b) => a - b);
    const median = wants.length % 2
      ? wants[wants.length >> 1]
      : (wants[wants.length / 2 - 1] + wants[wants.length / 2]) / 2;
    clamped = Math.abs(median) > maxShift;
    shift = Math.max(-maxShift, Math.min(maxShift, median));
  }

  const matches = syllables.map((f, i) =>
    matchSyllable(f, refsPerSyllable[i], { shift }));

  return { shift, shiftClamped: clamped, matches };
}
